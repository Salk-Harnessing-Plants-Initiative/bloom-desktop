// This method will be called when Electron has finished
// initialization and is ready to create browser windows.
// Some APIs can only be used after this event occurs.
app.on('ready', async () => {
  if (deploySelfTest) return;

  // Register the bloom-scan:// protocol handler BEFORE createWindow()'s
  // loadURL() call, closing the narrow race where the renderer could
  // request a bloom-scan:// resource before the handler exists (#93).
  protocol.handle(
    'bloom-scan',
    createScanProtocolHandler(() => loadEnvConfig(ENV_PATH).scans_dir)
  );

  createWindow();

  // Initialize idle timer for session auto-reset (default: 10 min, see idle-timer.ts)
  idleTimer = new IdleTimer({
    onIdle: () => {
      if (!hasSessionData()) return;
      console.log('[IdleTimer] Session idle timeout — resetting session state');
      resetSessionState();
      setWasIdleReset();
      if (mainWindow && !mainWindow.isDestroyed()) {
        mainWindow.webContents.send('session:idle-reset');
      }
    },
  });
  idleTimer.start();

  // Initialize database AFTER window is created so we can send errors to renderer
  try {
    console.log('[Main] Initializing database...');
    await initializeDatabaseAsync();
    console.log('[Main] Database initialized, registering handlers...');
    registerDatabaseHandlers({
      markMetadataDeleted,
      getMainWindow: () => mainWindow,
    });
    registerCylinderWaveHandlers({ ipcMain, db: getDatabase() });
    registerCylinderPlantHandlers({ ipcMain, db: getDatabase() });
    registerScanUploadAllHandlers({
      ipcMain,
      db: getDatabase(),
      createUploader: () => new ImageUploader(getDatabase()),
      getMainWindow: () => mainWindow,
    });
    console.log('[Main] Database initialized and handlers registered');

    // The species list for new experiments comes from Bloom: fetched now, in the
    // background, and saved next to the database for when Bloom can't be reached.
    // E2E runs use the built-in list and never call Bloom.
    const speciesStore = createSpeciesStore({
      file: path.join(path.dirname(getDatabasePath()), SAVED_SPECIES_FILE),
      fetchFromBloom: () => fetchBloomSpecies(loadEnvConfig(ENV_PATH)),
    });
    registerSpeciesHandlers({
      ipcMain,
      store: speciesStore,
      openExternal: (url) => shell.openExternal(url),
    });
    if (process.env.E2E_TEST !== 'true') void speciesStore.refresh();

    // Initialize GraviScan handlers if mode is graviscan
    try {
      const modeConfig = loadEnvConfig(ENV_PATH);
      await initGraviScan(
        modeConfig.scanner_mode || '',
        ipcMain,
        getDatabase(),
        () => mainWindow
      );
    } catch (graviErr) {
      console.error('[Main] Failed to initialize GraviScan:', graviErr);
    }

    // Send success message to renderer
    if (mainWindow && !mainWindow.isDestroyed()) {
      mainWindow.webContents.send('database:ready', { success: true });
    }
    resolveAppReady({ success: true });
  } catch (error) {
    const errorMessage = error instanceof Error ? error.message : String(error);
    const errorStack = error instanceof Error ? error.stack : undefined;
    console.error(
      '[Main] Failed to initialize database:',
      errorMessage,
      errorStack
    );
    resolveAppReady({ success: false, error: errorMessage });

    // Send error to renderer so user can see it in DevTools
    if (mainWindow && !mainWindow.isDestroyed()) {
      mainWindow.webContents.send('database:error', {
        error: errorMessage,
        stack: errorStack,
      });
    }
  }

  await initializePythonProcess();

  // Initialize scanner identity from config
  try {
    const config = loadEnvConfig(ENV_PATH);

    if (config.slack_webhook_url) {
      process.env.BLOOM_GRAVISCAN_SLACK_WEBHOOK_URL = config.slack_webhook_url;
      // Confirm to the rig admin that the URL was loaded WITHOUT logging the
      // URL itself (it's a secret).
      console.log('[GraviScan] Slack webhook URL loaded from ~/.bloom/.env');
    } else {
      console.log(
        '[GraviScan] BLOOM_GRAVISCAN_SLACK_WEBHOOK_URL not set — Slack notifications disabled'
      );
    }
    if (config.libusb_endpoint_recovery !== undefined) {
      process.env.LIBUSB_ENDPOINT_RECOVERY = String(
        config.libusb_endpoint_recovery
      );
      console.log(
        `[GraviScan] LIBUSB_ENDPOINT_RECOVERY explicitly set to: ${config.libusb_endpoint_recovery}`
      );
    } else {
      console.log(
        '[GraviScan] LIBUSB_ENDPOINT_RECOVERY not set in env — wrapper defaults to ON'
      );
    }
    if (config.graviscan_system_name) {
      process.env.GRAVISCAN_SYSTEM_NAME = config.graviscan_system_name;
      console.log(
        `[GraviScan] GRAVISCAN_SYSTEM_NAME loaded from ~/.bloom/.env: ${config.graviscan_system_name}`
      );
    } else {
      console.log(
        '[GraviScan] GRAVISCAN_SYSTEM_NAME not set — uploads/Box backup will omit system-name attribution'
      );
    }

    scannerIdentity.name = config.scanner_name || '';
    console.log(
      '[Scanner Identity] Initialized:',
      scannerIdentity.name || '(not configured)'
    );
  } catch (error) {
    console.error('[Scanner Identity] Failed to initialize:', error);
    scannerIdentity.name = '';
  }
});

